/**
 * PLAN.md phase 2. Two items, both of which had a dead end that looked alive:
 *
 *   ٢-١ export the container to Documents/NovaPC. The app shipped a Blob download, which
 *        is correct in a browser and does nothing inside the APK -- a WebView only
 *        downloads through a DownloadListener, and MainActivity installs none.
 *   ٢-٥ route status. The screen has to show ✅ / ⚠️ / ⛔, and the temptation is to show
 *        ✅ for things a web app cannot check (installed packages, driver versions).
 */
const docs = { Documents: 'DOCUMENTS' };
const fakeFs = (behaviour: 'ok' | 'throw' = 'ok') => {
  const writes: unknown[] = [];
  const mkdirs: unknown[] = [];
  return {
    writes,
    mkdirs,
    Filesystem: {
      mkdir: async (o: unknown) => {
        mkdirs.push(o);
      },
      writeFile: async (o: unknown) => {
        if (behaviour === 'throw') throw new Error('EACCES');
        writes.push(o);
        return { uri: 'file:///storage/emulated/0/Documents/NovaPC/T.container.json' };
      },
    },
  };
};

describe('PLAN ٢-١ — the container reaches shared storage', () => {
  it('writes Documents/NovaPC/<name> in the native lane', async () => {
    const f = fakeFs();
    const r = await exportContainer('T.container.json', '{"a":1}', {
      native: true,
      Filesystem: f.Filesystem,
      Directory: docs,
    });
    expect(r).toMatchObject({ ok: true, lane: 'documents' });
    expect(f.writes).toHaveLength(1);
    expect(f.writes[0]).toMatchObject({
      path: `${EXPORT_DIR}/T.container.json`,
      directory: 'DOCUMENTS',
      encoding: 'utf8',
    });
    expect(f.mkdirs[0]).toMatchObject({ path: EXPORT_DIR, recursive: true });
  });

  it('reports the URI Winlator guidance needs, not just "saved"', async () => {
    const f = fakeFs();
    const r = await exportContainer('T.container.json', '{}', {
      native: true,
      Filesystem: f.Filesystem,
      Directory: docs,
    });
    expect(r.where).toContain('Documents/NovaPC');
    expect(describeExport(r)).toContain('Winlator');
  });

  it('counts the bytes it wrote', async () => {
    const f = fakeFs();
    const text = '{"name":"لعبة"}'; // multibyte: bytes != characters
    const r = await exportContainer('T.container.json', text, {
      native: true,
      Filesystem: f.Filesystem,
      Directory: docs,
    });
    expect(r.bytes).toBe(new TextEncoder().encode(text).length);
    expect(r.bytes).toBeGreaterThan(text.length);
  });

  it('a failed native write does not report success', async () => {
    const f = fakeFs('throw');
    const copied: string[] = [];
    const r = await exportContainer('T.container.json', '{"a":1}', {
      native: true,
      Filesystem: f.Filesystem,
      Directory: docs,
      copy: async (t) => {
        copied.push(t);
      },
    });
    expect(r.ok).toBe(true);
    expect(r.lane, 'must fall to the clipboard lane, not pretend').toBe('clipboard');
    expect(r.error).toContain('EACCES');
    expect(copied).toHaveLength(1);
  });

  it('with no lane at all it says so, and says why', async () => {
    const r = await exportContainer('T.container.json', '{}', { native: true });
    expect(r).toMatchObject({ ok: false, lane: 'failed' });
    expect(describeExport(r)).toContain('فشل');
  });

  it('in a browser it uses the download lane, not the filesystem', async () => {
    const downloaded: string[] = [];
    const r = await exportContainer('T.container.json', '{}', {
      native: false,
      browserDownload: (name) => {
        downloaded.push(name);
      },
    });
    expect(r.lane).toBe('download');
    expect(downloaded).toEqual(['T.container.json']);
  });

  it('native detection is a real capability check, not a guess', () => {
    expect(isNativeShell({ Capacitor: { isNativePlatform: () => true } })).toBe(true);
    expect(isNativeShell({ Capacitor: { isNativePlatform: () => false } })).toBe(false);
    expect(isNativeShell(undefined)).toBe(false);
    // a broken Capacitor must not throw on the boot path
    expect(
      isNativeShell({
        Capacitor: {
          isNativePlatform: () => {
            throw new Error('boom');
          },
        },
      }),
    ).toBe(false);
  });

  it('the Android project registers the plugin and the permission it needs', () => {
    const gradle = readFileSync('android/app/capacitor.build.gradle', 'utf8');
    expect(gradle).toContain("project(':capacitor-filesystem')");
    /*
     * capacitor.plugins.json is GENERATED by `cap sync` and git-ignored (check 1.8's rule),
     * so it is read behind existsSync: on a clean checkout before a sync it is absent, and
     * that is not a failure of the app -- the gradle file above is the tracked evidence.
     */
    const pluginsFile = 'android/app/src/main/assets/capacitor.plugins.json';
    if (existsSync(pluginsFile)) {
      const plugins = JSON.parse(readFileSync(pluginsFile, 'utf8')) as { pkg: string }[];
      expect(plugins.map((p) => p.pkg)).toContain('@capacitor/filesystem');
    }
    const manifest = readFileSync('android/app/src/main/AndroidManifest.xml', 'utf8');
    expect(manifest).toContain('WRITE_EXTERNAL_STORAGE');
    // and it must be scoped, so modern devices are not asked for a dead permission
    expect(manifest).toMatch(/WRITE_EXTERNAL_STORAGE[\s\S]{0,80}maxSdkVersion="28"/);
  });
});

describe('PLAN ٢-٥ — the route screen never shows a tick it did not earn', () => {
  const base = { answers: {}, freeBytes: 8 * 1024 ** 3, needGB: 2, native: true };

  it('shows ✅ only for what was measured or confirmed', () => {
    const r = evaluateRoute(base);
    const byId = Object.fromEntries(r.requirements.map((x) => [x.id, x.state]));
    expect(byId.winlator).toBe('unknown'); // cannot list packages
    expect(byId.turnip).toBe('unknown'); // cannot read a driver version
    expect(byId.space).toBe('ok'); // this one we measured
    expect(byId.game).toBe('unknown');
  });

  it('confirms turn "unknown" into ok or missing', () => {
    const ok = evaluateRoute({ ...base, answers: { winlator: true, turnip: true, game: true } });
    expect(ok.verdict).toBe('ready');
    expect(ok.requirements.every((r) => r.state === 'ok')).toBe(true);
    const miss = evaluateRoute({ ...base, answers: { winlator: false } });
    expect(miss.verdict).toBe('partial');
    expect(miss.title).toContain('Winlator');
  });

  it('⛔ wins over ⚠️: no space blocks the route outright', () => {
    const r = evaluateRoute({ ...base, freeBytes: 1 * 1024 ** 3, answers: { winlator: true } });
    expect(r.verdict).toBe('blocked');
    expect(r.title).toContain('لا مساحة');
    expect(r.needGB).toBe(Math.ceil(2 + CONTAINER_GB));
  });

  it('when free space is unmeasurable it says so instead of guessing', () => {
    const r = evaluateRoute({ ...base, freeBytes: null });
    const space = r.requirements.find((x) => x.id === 'space')!;
    expect(space.state).toBe('never');
    expect(space.why).toContain('لا يفصح');
    expect(r.verdict).not.toBe('blocked');
  });

  it('needs the container space on top of the game, not instead of it', () => {
    expect(evaluateRoute({ ...base, needGB: 118 }).needGB).toBe(Math.ceil(118 + CONTAINER_GB));
  });

  it('every state has one label, so four screens cannot disagree', () => {
    expect(Object.keys(STATE_LABEL).sort()).toEqual(['missing', 'never', 'ok', 'unknown']);
    expect(STATE_LABEL.ok.mark).toBe('✅');
    expect(STATE_LABEL.missing.mark).toBe('⛔');
    // 'never' must not borrow the warning or the tick
    expect(STATE_LABEL.never.mark).not.toBe('✅');
    expect(STATE_LABEL.never.mark).not.toBe('⚠️');
  });

  it('the screen asks the user instead of faking the two unknowables', () => {
    const src = readFileSync('src/apps/GameSetupApp.tsx', 'utf8');
    expect(src).toContain('evaluateRoute');
    expect(src).toContain('state === \'unknown\'');
    expect(src).toContain('عندي'); // the confirm button
  });
});

describe('PLAN ٢-٤ — sources carry a version and a verification date', () => {
  it('every source states what it was checked against and when', async () => {
    const { SOURCES } = await import('../src/system/winePrefix');
    expect(SOURCES.length).toBeGreaterThanOrEqual(4);
    for (const s of SOURCES) {
      expect(s.version, `${s.name} has no version`).toMatch(/\S/);
      expect(s.released).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      expect(s.verified).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      expect(s.assets).toBeGreaterThan(0);
      // a version and its date must not contradict each other
      expect(Date.parse(s.verified)).toBeGreaterThanOrEqual(Date.parse(s.released));
      // and we link to the release page, never to a binary we would be redistributing
      expect(s.url).toMatch(/github\.com\/[^/]+\/[^/]+\/releases$/);
    }
  });

  it('a source older than the threshold is flagged, a fresh one is not', async () => {
    const { daysSince, staleSources, SOURCE_STALE_DAYS } = await import('../src/system/winePrefix');
    const now = Date.parse('2026-11-27T00:00:00Z');
    const old = {
      name: 'old',
      url: 'https://github.com/x/y/releases',
      note: '',
      version: 'v1',
      released: '2024-01-01',
      assets: 1,
      verified: '2026-11-27',
    };
    const fresh = { ...old, name: 'fresh', released: '2026-11-01' };
    expect(daysSince(old.released, now)).toBeGreaterThan(SOURCE_STALE_DAYS);
    expect(staleSources(now, [old, fresh]).map((s) => s.name)).toEqual(['old']);
  });

  it('the Turnip driver is the one flagged stale, and the app says so', async () => {
    // winlator_v25.1_r2 was released 2025-02-17: more than a year before this audit
    const { SOURCES, staleSources } = await import('../src/system/winePrefix');
    const stale = staleSources(Date.parse('2026-11-27T00:00:00Z'), SOURCES).map((s) => s.name);
    expect(stale).toContain('K11MCH1/WinlatorTurnipDrivers');
    const src = readFileSync('src/apps/GameSetupApp.tsx', 'utf8');
    expect(src).toContain('daysSince(s.released)');
    expect(src).toContain('إصدار قديم');
  });
});

describe('PLAN ٢-٢ — the native launch lane is wired to real platform calls', () => {
  const kt = readFileSync('android/app/src/main/java/os/nova/shell/NativeLaunchPlugin.kt', 'utf8');
  const manifest = readFileSync('android/app/src/main/AndroidManifest.xml', 'utf8');
  const paths = readFileSync('android/app/src/main/res/xml/file_paths.xml', 'utf8');
  const main = readFileSync('android/app/src/main/java/os/nova/shell/MainActivity.java', 'utf8');

  it('registers the plugin before the bridge starts', () => {
    expect(main).toContain('registerPlugin(NativeLaunchPlugin.class)');
    expect(main.indexOf('registerPlugin(NativeLaunchPlugin.class)')).toBeLessThan(
      main.indexOf('super.onCreate'),
    );
  });

  it('declares the packages Android 11+ would otherwise hide', () => {
    // without <queries>, getPackageInfo throws on Android 13 even when Winlator IS installed
    expect(manifest).toContain('<queries>');
    for (const pkg of ['com.winlator', 'com.winlator.star', 'app.gamenative']) {
      expect(manifest, `${pkg} not declared in <queries>`).toContain(`android:name="${pkg}"`);
    }
  });

  it('shares the folder the container is actually exported to', () => {
    /*
     * FileProvider throws IllegalArgumentException for any path outside a declared root.
     * Note what "outside" means: androidx FileProvider.java:524 maps <external-path> to
     * Environment.getExternalStorageDirectory() (/sdcard), so the template's
     * external-path "." ALREADY covers Documents/NovaPC. I first wrote this test claiming
     * it did not; the source corrected me. The explicit entry is an intentional narrowing,
     * and this test asserts a root exists that covers the export folder -- by either route.
     */
    /*
     * Not `toContain('Documents/NovaPC')`: the string also appears in this file's own
     * XML comment, so deleting the actual <external-path> left the assertion green.
     * Parse the elements and look for a root whose path covers the export folder.
     */
    const roots = [...paths.matchAll(/<(external-path|external-files-path|cache-path|files-path)[^>]*path="([^"]*)"/g)].map(
      (m) => ({ tag: m[1], path: m[2] }),
    );
    const covers = roots.some((r) => r.path.startsWith('Documents/NovaPC'));
    expect(covers, `no FileProvider root covers Documents/NovaPC (roots: ${JSON.stringify(roots)})`).toBe(true);
    const authority = /android:authorities="\$\{applicationId\}\.fileprovider"/.test(manifest);
    expect(authority).toBe(true);
  });

  it('the plugin uses the Kotlin API that exists, not a remembered one', () => {
    // matched against capacitor Bridge.java:440 / PluginCall.java:47,108
    expect(kt).toContain('import com.getcapacitor.Plugin');
    expect(kt).toContain('import com.getcapacitor.PluginCall');
    expect(kt).toContain('@CapacitorPlugin(name = "NativeLaunch")');
    expect(kt).toMatch(/call\.resolve\(/);
    expect(kt).toMatch(/call\.reject\(/);
    // a missing package is data, not an exception that escapes
    expect(kt).toContain('NameNotFoundException');
    expect(kt).toMatch(/catch \(_:\s*PackageManager\.NameNotFoundException\)/);
  });

  it('never leaves a dead button: the no-host case returns a reason', () => {
    expect(kt).toContain('no host app installed');
    expect(kt).toContain('storeUrl');
  });

  it('the JS side reports unavailability instead of guessing', async () => {
    const { detectHost, openInHost } = await import('../src/system/nativeLaunch');
    // no window.Capacitor in a Node test: both must answer honestly
    const host = await detectHost();
    expect(host).toEqual({ available: false, installed: [], version: '' });
    const r = await openInHost('Documents/NovaPC/x.container.json');
    expect(r.launched).toBe(false);
    expect(r.reason).toContain('الهاتف');
    expect(r.storeUrl).toContain('github.com');
  });
});

describe('PLAN ٢-٣ — what we accept from another app', () => {
  it('accepts the four kinds it can use and names the reason for anything else', async () => {
    const { classifyShare, ACCEPTED_EXT } = await import('../src/system/nativeLaunch');
    expect(classifyShare({ name: 'GAME.EXE', uri: 'content://x' })).toEqual({ accept: true, kind: 'program' });
    expect(classifyShare({ name: 'doom.com', uri: 'content://x' })).toEqual({ accept: true, kind: 'program' });
    expect(classifyShare({ name: 'disk.img', uri: 'content://x' })).toEqual({ accept: true, kind: 'image' });
    expect(classifyShare({ name: 'cd.iso', uri: 'content://x' })).toEqual({ accept: true, kind: 'image' });
    expect(classifyShare({ name: 'pack.zip', uri: 'content://x' })).toEqual({ accept: true, kind: 'archive' });
    const bad = classifyShare({ name: 'photo.jpg', uri: 'content://x' });
    expect(bad.accept).toBe(false);
    if (!bad.accept) expect(bad.reason).toContain('jpg');
    expect(ACCEPTED_EXT).toEqual(['.exe', '.com', '.img', '.iso', '.zip']);
  });

  /**
   * The defect this check exists for: the manifest declared the intent filters and the
   * classifier was tested, yet nothing read the activity's intent. A shared .exe opened
   * the app and did nothing -- and the previous test still passed, because it only ever
   * looked at a pure function. These three pin the missing half of the lane.
   */
  it('the activity actually reads the incoming intent', () => {
    const java = readFileSync('android/app/src/main/java/os/nova/shell/MainActivity.java', 'utf8');
    expect(java).toContain('getIntent()');
    expect(java).toMatch(/onNewIntent\s*\(\s*Intent/);
    expect(java).toContain('stash');
    // a manifest filter with no reader is the exact bug, so the pair is asserted together
    const xml = readFileSync('android/app/src/main/AndroidManifest.xml', 'utf8');
    expect(xml).toContain('android.intent.action.SEND');
    // singleTask is what routes the second share into onNewIntent rather than onCreate
    expect(xml).toContain('android:launchMode="singleTask"');
  });

  it('the plugin exposes the share exactly once', () => {
    const kt = readFileSync('android/app/src/main/java/os/nova/shell/NativeLaunchPlugin.kt', 'utf8');
    expect(kt).toContain('fun takePendingShare');
    // Clearing must happen *on read*, not in one branch: the first version cleared it
    // only inside the no-stream path, and my earlier assertion ("body contains
    // 'pending = null'") passed because that string existed elsewhere. Anchored to the
    // read itself now, which is the only placement that cannot be satisfied by accident.
    expect(kt).toMatch(/val intent = pending\s*\n(?:\s*\/\/[^\n]*\n)*\s*pending = null/);
    // and exactly one clear site, so "cleared" cannot mean "cleared somewhere else"
    expect(kt.match(/pending = null/g)?.length).toBe(1);
    expect(kt).toContain('EXTRA_STREAM');
    expect(kt).toContain('DISPLAY_NAME');
    // The launcher intent must not be kept, or every cold start looks like a share.
    // The first version of this line matched any ACTION_SEND followed by any "return"
    // within 400 chars, so a mutation replacing the guard with `if (false)` passed it.
    // Anchored to the guard's own body now.
    expect(kt).toMatch(
      /if \(action != Intent\.ACTION_SEND && action != Intent\.ACTION_VIEW\) \{[\s\S]{0,300}?return\s*\n\s*\}/,
    );
  });

  it('detect() survives an empty package list instead of throwing', () => {
    const kt = readFileSync('android/app/src/main/java/os/nova/shell/NativeLaunchPlugin.kt', 'utf8');
    // JSArray.getString(0) throws on an empty array; the old code called it unconditionally
    expect(kt).not.toMatch(/installedVersion\(found\.getString\(0\)/);
    expect(kt).toMatch(/found\.length\(\)\s*>\s*0/);
  });

  it('judgeShare refuses a name/type disagreement instead of guessing', async () => {
    const { judgeShare } = await import('../src/system/nativeLaunch');
    const ok = judgeShare({ name: 'GAME.EXE', uri: 'content://x', type: 'application/x-msdownload' });
    expect(ok.accept).toBe(true);
    // a sender can name anything .exe; the type is the second opinion
    const lie = judgeShare({ name: 'holiday.exe', uri: 'content://x', type: 'image/jpeg' });
    expect(lie.accept).toBe(false);
    if (!lie.accept) expect(lie.reason).toContain('image/jpeg');
    // a generic type carries no information, so the name decides and is not penalised
    expect(judgeShare({ name: 'pack.zip', uri: 'content://x', type: 'application/octet-stream' }).accept).toBe(true);
    // no type at all is the normal case for a file manager's share sheet
    expect(judgeShare({ name: 'disk.img', uri: 'content://x' }).accept).toBe(true);
    expect(judgeShare({ name: 'cd.iso', uri: 'content://x', type: 'application/x-iso9660-image' }).accept).toBe(true);
  });

  it('the browser build says it cannot receive files rather than pretending', async () => {
    const { takeSharedFile } = await import('../src/system/nativeLaunch');
    const r = await takeSharedFile();
    expect(r.pending).toBe(false);
    expect(r.reason).toContain('المتصفح');
  });

  it('two callers both see the shared file', async () => {
    /*
     * App.tsx opens the window, GameSetupApp.tsx renders the verdict. The native read
     * clears the intent, so the first version of this lane made the second caller see
     * "nothing" and the window opened empty -- the share was received and then dropped a
     * layer later. The cache is what makes the second caller honest; this asserts it.
     */
    const mod = await import('../src/system/nativeLaunch');
    mod.__resetSharedFileCache();
    const fake = {
      pending: true,
      name: 'GAME.EXE',
      type: 'application/x-msdownload',
      uri: 'content://downloads/1',
    };
    let asked = 0;
    mod.__setNativeLaunchForTest({
      detect: async () => ({ available: false, installed: [], version: '' }),
      openContainer: async () => ({ launched: false }),
      takePendingShare: async () => {
        asked += 1;
        return fake;
      },
    });
    try {
      const first = await mod.takeSharedFile();
      const second = await mod.takeSharedFile();
      expect(first.pending).toBe(true);
      expect(second).toEqual(first);
      // the native side clears the intent on read, so asking twice must not be how this
      // works: exactly one call, and both callers answered from it
      expect(asked).toBe(1);
      expect(second.name).toBe('GAME.EXE');
    } finally {
      mod.__setNativeLaunchForTest(null);
      mod.__resetSharedFileCache();
    }
  });
});

describe('the Android XML is parseable XML, not just plausible text', () => {
  /**
   * A double hyphen inside an XML comment is illegal, and I wrote one in BOTH files this
   * cycle ("-- maxSdkVersion", "-- a false negative"). The manifest is read by aapt at
   * build time, so this would have failed the APK build with a message about an invalid
   * token, not about the comment. Parsed here so the failure happens in the suite.
   */
  const parse = (p: string) => {
    const text = readFileSync(p, 'utf8');
    // no XML parser in Node's stdlib; these two rules are what invalidated the files
    const comments = [...text.matchAll(/<!--([\s\S]*?)-->/g)].map((m) => m[1]);
    for (const c of comments) {
      expect(c.includes('--'), `${p}: "--" inside an XML comment`).toBe(false);
      expect(c.endsWith('-'), `${p}: comment ends with "-"`).toBe(false);
    }
    // tag balance: strip comments first, then count only real opening tags
    const stripped = text.replace(/<!--[\s\S]*?-->/g, '');
    const opens = [...stripped.matchAll(/<([a-zA-Z][\w:.-]*)(\s[^<>]*)?>/g)].filter(
      (m) => !(m[2] ?? '').trimEnd().endsWith('/'),
    );
    const closes = [...stripped.matchAll(/<\/([a-zA-Z][\w:.-]*)>/g)];
    expect(opens.length, `${p}: ${opens.length} opens vs ${closes.length} closes`).toBe(closes.length);
    // and they must nest in order, not merely be equal in number
    const stack: string[] = [];
    for (const m of stripped.matchAll(/<(\/?)([a-zA-Z][\w:.-]*)(\s[^<>]*)?(\/?)>/g)) {
      const [, closing, name, attrs, selfClose] = m;
      if (selfClose || (attrs ?? '').trimEnd().endsWith('/')) continue;
      if (closing) expect(stack.pop(), `${p}: </${name}> closes the wrong element`).toBe(name);
      else stack.push(name);
    }
    expect(stack, `${p}: unclosed elements`).toEqual([]);
    return text;
  };

  it('AndroidManifest.xml has legal comments and balanced tags', () => {
    const t = parse('android/app/src/main/AndroidManifest.xml');
    expect(t.trimEnd().endsWith('</manifest>')).toBe(true);
  });

  it('file_paths.xml has legal comments and balanced tags', () => {
    parse('android/app/src/main/res/xml/file_paths.xml');
  });

  it('the share-in filters PLAN ٢-٣ needs are present', () => {
    const t = readFileSync('android/app/src/main/AndroidManifest.xml', 'utf8');
    expect(t).toContain('android.intent.action.SEND');
    expect(t).toContain('android.intent.action.VIEW');
    // a VIEW filter without BROWSABLE still works from a file manager, but SEND needs DEFAULT
    expect(t).toContain('android.intent.category.DEFAULT');
  });
});
