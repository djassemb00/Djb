# --- four-form letters: (inner body, connector on the left for fin/ini/med)
def four(cp, iso_rows, body_rows):
    """body_rows: 8 rows of the core shape without connectors; we add the
    horizontal join stroke on the left for final/initial/medial."""
    # Geometry, in right-to-left flow: the PREVIOUS letter sits to the right of
    # this cell (so a connection to it touches bit 7), and the NEXT letter sits
    # to the left (connection touches bit 0).
    #   initial = connects to next only  -> left edge
    #   final   = connects to prev only  -> right edge
    #   medial  = both edges
    fin = [row[:7] + "#" for row in body_rows]
    ini = ["#" + row[1:] for row in body_rows]
    med = ["#" + row[1:7] + "#" for row in body_rows]
    add(cp, iso_rows, fin, ini, med)

